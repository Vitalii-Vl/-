/**
 * @brief считывает целое число с клавиатуры с проверкой ввода.
 запрашивает у пользователя ввод целого числа и повторяет запрос,пока не будет введено корректное числовое значение
 Очищает буфер ввода в случае некорректного ввода.
 * @return Считанное целое число.
 */
int getValue() {
    int value;
    while (!(cin >> value)) {
        cout << "Ошибка ввода. Пожалуйста, введите целое число: ";
        cin.clear(); // Сброс флагов ошибки ввода (например, cin.fail())
        // Игнорировать остаток строки до символа новой строки, чтобы очистить буфер
        cin.ignore(numeric_limits<streamsize>::max(), '\n');
    }
    return value;
}

/**
 * @brief Безопасно считывает вещественное число с клавиатуры с проверкой ввода.
 Функция запрашивает у пользователя ввод вещественного числа и повторяет запрос
 пока не будет введено корректное числовое значение
 Очищает буфер ввода в случае некорректного ввода.
 * @return Считанное вещественное число типа double.
 */
double getDouble() {
    double value;
    // Цикл повторяется, пока ввод некорректен
    while (!(cin >> value)) {
        cout << "Ошибка ввода. Пожалуйста, введите вещественное число: ";
        cin.clear(); // Сброс флагов ошибки ввода
        cin.ignore(numeric_limits<streamsize>::max(), '\n'); // Очистка буфера
    }
    return value;
}

/**
 * @brief Проверяет, что введенное значение n (количество членов) удовлетворяет условию n >= 1.
 * @param n Проверяемое значение количества членов ряда.
 * @pre n должно быть числовым значением.
 * @post Если n < 1, программа завершается с кодом ошибки 1.
 */
void checkN(const int n) {
    if (n < 1) {
        cout << "Ошибка: Число членов ряда (n) должно быть не меньше 1. Программа будет завершена." << endl;
        exit(1); // Завершение программы с кодом ошибки
    }
}

/**
 * @brief Вычисляет следующий член ряда на основе текущего члена и его индекса.
 *
 * Использует рекуррентное соотношение: a_k = a_{k-1} * (-1) / (k^2).
 * Здесь 'i' представляет собой индекс текущего члена a_i,
 * и функция возвращает a_{i+1}.
 *
 * @param current_term Текущий член ряда (a_i).
 * @param i_k Индекс текущего члена ряда (i).
 * @return Следующий член ряда (a_{i+1}).
 */
double getNext(const double current_term, const int i_k) {
    // Вычисляем a_{i_k+1} на основе a_{i_k} и (i_k+1)^2
    return current_term * (-1.0) / (static_cast<double>(i_k + 1) * (i_k + 1));
}

/**
 * @brief Рассчитывает сумму первых n членов ряда.
 *
 * Ряд определяется формулой a_k = (-1)^k / (k!)^2, где k >= 1.
 * Вычисление производится итеративно с использованием рекуррентного выражения
 * для получения следующего члена ряда, что позволяет избежать прямого вычисления факториалов.
 *
 * @param n Заданное количество членов ряда.
 * @pre n >= 1.
 * @return Сумма первых n членов ряда.
 */
double sumN(const int n) {
    if (n == 0) return 0.0; // Крайний случай: если n=0, сумма равна 0.

    // Первый член ряда: a_1 = (-1)^1 / (1!)^2 = -1 / 1 = -1.0
    double current_term = -1.0;
    double total_sum = current_term; // Начинаем сумму с первого члена

    // Цикл для вычисления остальных n-1 членов ряда (a_2, ..., a_n)
    // i_k будет представлять индекс текущего члена, который находится в current_term.
    // На каждой итерации вычисляем a_{i_k+1} и добавляем его к сумме.
    for (int i_k = 1; i_k < n; ++i_k) {
        current_term = getNext(current_term, i_k); // current_term теперь a_{i_k+1}
        total_sum += current_term;
    }
    return total_sum;
}

/**
 * @brief Проверяет, что введенное значение e (точность) удовлетворяет условию e > 0.
 *
 * Если e меньше или равно нулю, функция выводит сообщение об ошибке
 * и принудительно завершает выполнение программы.
 *
 * @param e Проверяемое значение погрешности.
 * @pre e должно быть числовым значением.
 * @post Если e <= 0, программа завершается с кодом ошибки 1.
 */
void checkE(const double e) {
    if (e <= 0) { // Проверяем, что e строго больше нуля
        cout << "Ошибка: Погрешность (e) должна быть положительным числом. Программа будет завершена." << endl;
        exit(1); // Завершение программы с кодом ошибки
    }
}

/**
 * @brief Рассчитывает сумму членов ряда, по модулю не меньших заданного числа e.
 Ряд определяется формулой a_k*= (-1)^k / (k!)^2, где k >= 1.
 Вычисление прекращается, когда модуль очередного члена становится меньше e.
 * @param e Заданная точность.
 * @pre e > 0.
 * @return Сумма членов ряда, abs(a_k) >= e.
 */
double sumE(const double e) {
    double current_term = -1.0;
    double total_sum = 0.0; 
    int k_index = 1; 

    // Цикл продолжается, пока модуль текущего члена ряда не меньше e.
    // Если abs(current_term) < e сразу, то цикл не выполнится, и sum будет 0.0, что корректно.
    while (abs(current_term) >= e) {
        total_sum += current_term; // Добавляем текущий член к сумме
        k_index++; // Увеличиваем индекс для следующего члена
        current_term = getNext(current_term, k_index); // Вычисляем следующий член ряда
    }
    return total_sum;
}

